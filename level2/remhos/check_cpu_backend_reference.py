#!/usr/bin/env python3
"""Remhos: the FROZEN CPU-backend values of validate.sh Part B check 2.

validate.sh Part B compares each GPU case (-ho 3 -lo 5 -fct 2 -pa -d cuda) with the SAME configuration run on the
CPU backend of the same binary (-pa -d cpu): final mass within 1e-8 relative, max value within 1e-6 relative. That
CPU run is a recomputation of the scientific result, so it no longer runs on validate.sh's default path: its four
results were frozen ONCE, from one explicit offline run (HPCPERF_CPU_REFERENCE=1 validate.sh), in
reference/validate/cpu-backend-pa.json, and the default mode compares the GPU values with them at the same
tolerances (README "Validation", "Modes").

    check_cpu_backend_reference.py get <reference.json> <case> --args "<cpu args>" --tol-mass T --tol-max T
        validate.sh default mode: prints "<final mass> <max value>" of <case> (one line, the printed digits of
        the CPU run) and exits 0. Refuses (prints "ERROR: ...", exit 2) a missing / corrupted reference, another
        schema or benchmark, a case that is not frozen, a case whose recorded CPU command differs from <cpu args>
        (validate.sh passes the command its offline mode would run, mesh paths relative to level2/remhos), a mesh
        whose sha256 differs from the recorded one, and tolerances that differ from validate.sh's (the artifact
        cannot change the rule). It runs nothing and never regenerates the reference.
    check_cpu_backend_reference.py describe <reference.json>
        one provenance line (binary sha256, run date, log sha256s) for validate.sh's log.
    check_cpu_backend_reference.py freeze --out FILE --binary EXE --log-dir DIR --tol-mass T --tol-max T
                                    --case NAME "CPU ARGS" [--case ...] [--started UTC] [--finished UTC]
                                    [--launch TEXT] [--mode TEXT] [--log-kept-at TEXT] [--note TEXT] [--force]
        CONSTRUCTION TIME ONLY (never called by validate.sh): reads DIR/validate-NAME-cpu.log, written by an
        offline validate.sh run of the CPU backend, and writes the frozen file with its provenance (binary path,
        sha256 and mtime, MFEM config.mk sha256, git HEAD and whether the Remhos sources were clean, host, CPU
        model, Slurm job, launch line, per case the exact CPU command, mesh sha256, mass / max / mass loss /
        kernel time, the log's sha256, size and mtime). Refuses a log that is not a finished CPU-backend run
        of that configuration (no "Device configuration: cpu", another solver combination, no -pa, no final
        mass / max) and an existing file (--force overwrites).
"""
import hashlib, json, math, os, platform, re, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SCHEMA = "hpcperf-remhos-cpu-backend-reference-1"
NUM = r"([-+]?[0-9.]+(?:[eE][-+]?[0-9]+)?)"


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def utc(ts):
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(ts))


def mesh_of(args):
    a = args.split()
    if "-m" not in a or a.index("-m") + 1 >= len(a):
        raise ValueError(f"no -m <mesh> in {args!r}")
    return a[a.index("-m") + 1]


def die(msg):
    print(f"ERROR: {msg}")
    return 2


def load(path):
    try:
        d = json.load(open(path))
    except (OSError, ValueError) as ex:
        raise ValueError(f"frozen reference {path} unreadable ({ex}) -- it is made once offline, never regenerated by validate.sh")
    if not isinstance(d, dict) or d.get("schema") != SCHEMA or d.get("benchmark") != "remhos":
        raise ValueError(f"{path}: not a {SCHEMA} reference of remhos -- refused")
    rr = d.get("reference_run")
    if not isinstance(rr, dict) or not re.fullmatch(r"[0-9a-f]{64}", str(rr.get("binary_sha256", ""))):
        raise ValueError(f"{path}: reference_run.binary_sha256 missing -- provenance incomplete, refused")
    if not isinstance(d.get("cases"), dict) or not d["cases"]:
        raise ValueError(f"{path}: no cases -- corrupted reference refused")
    return d


def get(argv):
    if len(argv) < 2:
        return die("usage: get <reference.json> <case> --args ARGS --tol-mass T --tol-max T")
    path, case = argv[0], argv[1]
    opts = dict(zip(argv[2::2], argv[3::2]))
    for k in ("--args", "--tol-mass", "--tol-max"):
        if k not in opts:
            return die(f"get: {k} is required")
    try:
        d = load(path)
    except ValueError as ex:
        return die(str(ex))
    tol = d.get("tolerances") or {}
    want = {"mass_rel": float(opts["--tol-mass"]), "max_rel": float(opts["--tol-max"])}
    if tol != want:
        return die(f"{path}: tolerances {tol} differ from validate.sh's {want} -- refused (the artifact cannot change the rule)")
    c = d["cases"].get(case)
    if not isinstance(c, dict):
        return die(f"{path}: case {case!r} is not frozen (frozen: {', '.join(sorted(d['cases']))})")
    if c.get("args") != opts["--args"]:
        return die(f"{path}: case {case!r} was frozen for the CPU command {c.get('args')!r}, validate.sh would run "
                   f"{opts['--args']!r} -- the reference does not belong to this configuration; refused")
    mesh = mesh_of(c["args"])
    mpath = os.path.join(HERE, mesh)
    if not os.path.isfile(mpath):
        return die(f"mesh {mesh} missing")
    if sha256_file(mpath) != c.get("mesh_sha256"):
        return die(f"mesh {mesh} sha256 {sha256_file(mpath)[:16]}... differs from the frozen {str(c.get('mesh_sha256'))[:16]}... -- refused")
    vals = []
    for k in ("final_mass_u", "max_value_u"):
        v = c.get(k)
        if isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v):
            return die(f"{path}: case {case!r} field {k} missing or not finite -- corrupted reference refused")
        vals.append(repr(float(v)))
    print(" ".join(vals))
    return 0


def describe(argv):
    try:
        d = load(argv[0])
    except (ValueError, IndexError) as ex:
        return die(str(ex))
    rr = d["reference_run"]
    print(f"frozen CPU-backend reference {os.path.relpath(os.path.abspath(argv[0]), HERE)}: {len(d['cases'])} cases, "
          f"binary sha256 {rr['binary_sha256'][:12]}..., run finished {rr.get('finished_utc')}, "
          f"log sha256 " + ", ".join(f"{n} {c.get('log_sha256', '?')[:12]}..." for n, c in sorted(d["cases"].items())) +
          f"; generated {d.get('generated_utc')}")
    return 0


def git(*args):
    try:
        return subprocess.run(["git", "-C", REPO, *args], capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def freeze(argv):
    opts, cases, i = {}, [], 0
    while i < len(argv):
        a = argv[i]
        if a == "--force":
            opts["force"] = True; i += 1; continue
        if a == "--case" and i + 2 < len(argv):
            cases.append((argv[i + 1], argv[i + 2])); i += 3; continue
        if a.startswith("--") and i + 1 < len(argv):
            opts[a[2:].replace("-", "_")] = argv[i + 1]; i += 2; continue
        return die(f"freeze: unexpected argument {a!r}")
    for need in ("out", "binary", "log_dir", "tol_mass", "tol_max"):
        if need not in opts:
            return die(f"freeze: --{need.replace('_', '-')} is required")
    if not cases:
        return die("freeze: at least one --case NAME ARGS")
    out = opts["out"]
    if os.path.exists(out) and not opts.get("force"):
        return die(f"freeze: {out} exists (construction-time artifact; --force overwrites)")
    exe = opts["binary"]
    if not os.path.isfile(exe):
        return die(f"freeze: binary {exe} missing")
    frozen = {}
    for name, args in cases:
        log = os.path.join(opts["log_dir"], f"validate-{name}-cpu.log")
        if not os.path.isfile(log):
            return die(f"freeze: {log} missing")
        text = open(log, errors="replace").read()
        if not re.search(r"^Device configuration: cpu\s*$", text, re.M):
            return die(f"freeze: {log} is not a CPU-backend run (no 'Device configuration: cpu')")
        for opt in ("--device cpu", "--partial-assembly", "--ho-type 3", "--lo-type 5", "--fct-type 2"):
            if not re.search(r"^\s*" + re.escape(opt) + r"\s*$", text, re.M):
                return die(f"freeze: {log} lacks the option line {opt!r} -- not the Part B CPU configuration")
        a = args.split()
        if a[-2:] != ["-d", "cpu"] or "-pa" not in a:
            return die(f"freeze: case {name}: the CPU args must end with '-pa -d cpu' (got {args!r})")
        mesh = mesh_of(args)
        if not re.search(r"^\s*--mesh \S*/" + re.escape(os.path.basename(mesh)) + r"\s*$", text, re.M):
            return die(f"freeze: {log} did not run mesh {mesh}")
        m = re.findall(r"^Final mass u:\s+" + NUM, text, re.M)
        x = re.findall(r"^Max value u:\s+" + NUM, text, re.M)
        loss = re.findall(r"^Mass loss u:\s+" + NUM, text, re.M)
        kt = re.findall(r"^Total kernel time:\s+" + NUM, text, re.M)
        if not m or not x:
            return die(f"freeze: {log} has no final mass / max value -- unfinished run")
        mass, umax = float(m[-1]), float(x[-1])
        if not (math.isfinite(mass) and math.isfinite(umax)):
            return die(f"freeze: {log}: non-finite mass / max")
        st = os.stat(log)
        frozen[name] = {
            "args": args, "mesh": mesh, "mesh_sha256": sha256_file(os.path.join(HERE, mesh)),
            "final_mass_u": mass, "max_value_u": umax, "printed": {"final_mass_u": m[-1], "max_value_u": x[-1]},
            "mass_loss_u": float(loss[-1]) if loss else None, "total_kernel_time_s": float(kt[-1]) if kt else None,
            "device_banner": "Device configuration: cpu",
            "log": os.path.basename(log), "log_sha256": sha256_file(log), "log_bytes": st.st_size, "log_mtime_utc": utc(st.st_mtime)}
    config_mk = os.path.join(REPO, ".deps/install/mfem/share/mfem/config.mk")
    dirty = git("status", "--porcelain", "--", "level2/remhos/remhos*.cpp", "level2/remhos/remhos*.hpp", "level2/remhos/makefile",
                "level2/remhos/data")
    cpu_model = None
    try:
        cpu_model = next(l.split(":", 1)[1].strip() for l in open("/proc/cpuinfo") if l.startswith("model name"))
    except (OSError, StopIteration):
        pass
    est = os.stat(exe)
    ref = {
        "schema": SCHEMA, "benchmark": "remhos",
        "used_by": "level2/remhos/validate.sh Part B check 2, default mode (the GPU values vs these frozen CPU-backend values)",
        "what": ("final mass and max value of validate.sh Part B's four cases run on the CPU backend of the same binary "
                 "(-ho 3 -lo 5 -fct 2 -pa -d cpu, mpirun -np 1): the values the live check 2 compared with until 2026-10-27"),
        "tolerances": {"mass_rel": float(opts["tol_mass"]), "max_rel": float(opts["tol_max"])},
        "tolerance_basis": ("validate.sh Part B check 2, unchanged: GPU mass within 1e-8 and max within 1e-6 relative of the "
                            "CPU backend (observed: identical to the 10 printed digits in three cases, 9e-8 in max for "
                            "periodic-hexagon after 2000 nonlinear FCT steps). The frozen values ARE the CPU backend's output "
                            "(not a GPU golden), so no budget is subtracted: d0 = 0 (README 'Modes')."),
        "reference_run": {
            "implementation": "the CPU backend (MFEM Device 'cpu', host loops of the same mfem::forall kernels) of the CUDA build",
            "binary": os.path.relpath(os.path.abspath(exe), REPO), "binary_sha256": sha256_file(exe),
            "binary_bytes": est.st_size, "binary_mtime_utc": utc(est.st_mtime),
            "build": "level2/remhos/build.sh CUDA (upstream makefile, MFEM v4.10 .deps/install/mfem)",
            "mfem_config_mk_sha256": sha256_file(config_mk) if os.path.isfile(config_mk) else None,
            "git_head": git("rev-parse", "HEAD"), "remhos_sources_clean": (dirty == "") if dirty is not None else None,
            "host": platform.node().split(".")[0], "cpu_model": cpu_model,
            "slurm_job": os.environ.get("SLURM_JOB_ID"),
            "mode": opts.get("mode"), "launch": opts.get("launch"),
            "started_utc": opts.get("started"), "finished_utc": opts.get("finished"),
            "log_kept_at": opts.get("log_kept_at")},
        "cases": frozen,
        "generated_utc": utc(time.time()),
        "generated_by": "level2/remhos/check_cpu_backend_reference.py freeze (construction-time; from the offline run's logs, no rerun)",
        "note": opts.get("note"),
    }
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w") as fh:
        json.dump(ref, fh, indent=1, sort_keys=True)
        fh.write("\n")
    print(f"wrote {out}: " + "; ".join(f"{n} mass {c['printed']['final_mass_u']} max {c['printed']['max_value_u']}" for n, c in frozen.items()))
    return 0


def main(argv):
    cmds = {"get": get, "describe": describe, "freeze": freeze}
    if len(argv) < 2 or argv[1] not in cmds:
        print(__doc__)
        return 2
    return cmds[argv[1]](argv[2:])


if __name__ == "__main__":
    sys.exit(main(sys.argv))
