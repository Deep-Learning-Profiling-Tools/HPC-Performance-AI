#!/usr/bin/env bash
# Build Cholla (v3.0.0, the hydro build type) with upstream's GNU Makefile on the GPU.
#
#   ./build.sh [CUDA]
#
# Layout (one frozen source tree, generated state isolated per backend profile):
#   source   level3/cholla/src (frozen source bundle materialized by tools/prepare_benchmark.sh; identity in
#            provenance/; backend-independent) -- read ONLY; nothing is fetched, cloned or patched here
#   profile  <cuda> (override HPCPERF_CHOLLA_PROFILE; must name the backend)
#   build    build/level3/cholla/<profile>/src   a copy of src/ with the generated host file builds/make.host.hpcperf
#            (upstream's Makefile writes objects next to the sources and the binary to bin/)
#   install  .deps/level3/cholla/<profile>/install/bin/cholla (+ .hpcperf-l3-fingerprint), logs under
#            .deps/level3/cholla/<profile>/logs
#
# Recipe = upstream's `make TYPE=hydro MACHINE=<host>`: builds/make.type.hydro (upstream, unchanged: MPI_CHOLLA,
# PRECISION=2, PLMC reconstruction, HLLC Riemann solver, VL integrator, density/temperature floors, HDF5 output)
# with a generated host file in the style of upstream's builds/make.host.* (class A, a build-side configuration
# file): CXX = mpicxx (conda GCC 13.3 + Open MPI 5.0.10), nvcc with -ccbin=mpicxx, CUDA_ARCH = sm_<arch>,
# HDF5_ROOT/MPI_ROOT = the conda environment, CUDA_ROOT = the toolkit of the nvcc on PATH; upstream's optimize
# flags (-Ofast host, -O3 device, --expt-extended-lambda -fmad=false from the Makefile) plus -fPIE / -Xcompiler
# -fPIE (the conda GCC links position-independent executables; nvcc's host objects must match). GIT_HASH is
# passed as the frozen upstream commit (provenance/upstream.lock; the one class-D Makefile patch of the bundle
# makes it a make variable -- upstream static_asserts a 40-character hash and the bundle is not a git checkout).
# The conda build variables (CFLAGS/LDFLAGS/...) are cleared as for every Level 3 build.
#
# Environment overrides:
#   HPCPERF_CUDA_ARCH   numeric compute capability (default: detected)
#   HPCPERF_BUILD_JOBS  parallel jobs (default 16)
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
R="$(cd "$HERE/../.." && pwd)"
set +u; # shellcheck disable=SC1091
source "$R/hpcperf_env.sh" 2>/dev/null || true; set -u
# shellcheck disable=SC1091
source "$R/level3/tools/l3_common.sh"
l3_isolate_build_env
l3_clean_conda_build_env

BACKEND="$(echo "${1:-CUDA}" | tr '[:lower:]' '[:upper:]')"
case "$BACKEND" in CUDA) ;; HIP) echo "build.sh: HIP: untested here (no ROCm); upstream's HIP recipe is builds/make.host.frontier" >&2; exit 1;; *) echo "usage: $0 [CUDA]" >&2; exit 2;; esac
MODEL="$(echo "$BACKEND" | tr '[:upper:]' '[:lower:]')"
l3_require_materialized "$HERE" || exit 3
SRC="$HERE/src"
[ -f "$SRC/Makefile" ] && [ -f "$SRC/src/main.cpp" ] || { echo "build.sh: $SRC is not a Cholla source tree -- run tools/prepare_benchmark.sh level3 cholla" >&2; exit 3; }
SHA="$(l3_source_commit "$HERE")"; TREE_SHA="$(l3_source_tree_sha "$HERE")"
PROFILE="$(l3_backend_profile CHOLLA "$MODEL")"
l3_paths_profile cholla "$PROFILE" "$MODEL" || exit 2
JOBS="${HPCPERF_BUILD_JOBS:-16}"
ARCH="${HPCPERF_CUDA_ARCH:-$(l3_gpu_arch)}"
CUDA_ROOT="$(cd "$(dirname "$(command -v nvcc)")/.." && pwd)"
CONDA="${CONDA_PREFIX:?build.sh: CONDA_PREFIX unset (source hpcperf_env.sh)}"
command -v mpicxx >/dev/null || { echo "build.sh: mpicxx not on PATH" >&2; exit 3; }
[ -f "$CONDA/include/hdf5.h" ] || { echo "build.sh: HDF5 headers not in $CONDA/include" >&2; exit 3; }
[ ${#SHA} -eq 40 ] || { echo "build.sh: the frozen upstream commit ($SHA) is not a 40-character hash" >&2; exit 3; }

FLAGS="TYPE=hydro MACHINE=hpcperf host(mpicxx -Ofast -fPIE) gpu(nvcc -O3 -ccbin=mpicxx -Xcompiler -fPIE -fmad=false sm_$ARCH) hdf5+mpi=conda"
FP="$(l3_fingerprint_text cholla "$SHA" "$MODEL" "cuda=$(nvcc --version | sed -n 's/.*release \([0-9.]*\).*/\1/p' | head -1)" "$FLAGS" "runtime(1 rank per GPU, MPI_CHOLLA)")"
l3_fingerprint_check "$L3_INSTALL" "$FP" || exit 1

echo "# Cholla $BACKEND profile=$PROFILE: upstream $SHA (frozen source tree $TREE_SHA), sm_$ARCH, MPI $(mpirun --version 2>/dev/null | head -1), HDF5 $CONDA"
mkdir -p "$L3_BUILD" "$L3_INSTALL/bin" "$L3_LOGS"
B="$L3_BUILD/src"
rm -rf "$B"; mkdir -p "$B"
rsync -a --exclude='.git' "$SRC/" "$B/"          # upstream builds in place (objects next to the sources, bin/)
cat > "$B/builds/make.host.hpcperf" <<HOST
#-- HPC-Performance-AI host file (generated by level3/cholla/build.sh; style of upstream's builds/make.host.*)
CXX               = mpicxx
CXXFLAGS_DEBUG    = -g -O0 -std=c++17 -fPIE
CXXFLAGS_OPTIMIZE = -Ofast -std=c++17 -fPIE
GPUFLAGS_DEBUG    = -g -O0 -std=c++17 -ccbin=mpicxx -Xcompiler -fPIE
GPUFLAGS_OPTIMIZE = -g -O3 -std=c++17 -ccbin=mpicxx -Xcompiler -fPIE
CUDA_ARCH         = sm_$ARCH
CUDA_ROOT         = $CUDA_ROOT
HDF5_ROOT         = $CONDA
MPI_ROOT          = $CONDA
HOST
t0=$(date +%s)
( cd "$B" && make -j "$JOBS" TYPE=hydro MACHINE=hpcperf GIT_HASH="$SHA" > "$L3_LOGS/build-$MODEL.log" 2>&1 ) \
    || { tail -30 "$L3_LOGS/build-$MODEL.log"; echo "build.sh: make failed (log: $L3_LOGS/build-$MODEL.log)" >&2; exit 1; }
[ -x "$B/bin/cholla.hydro.hpcperf" ] || { echo "build.sh: $B/bin/cholla.hydro.hpcperf not produced" >&2; exit 1; }
cp -f "$B/bin/cholla.hydro.hpcperf" "$L3_INSTALL/bin/cholla"
l3_fingerprint_write "$L3_INSTALL" "$FP"
echo "# built in $(( $(date +%s)-t0 )) s: $L3_INSTALL/bin/cholla (make TYPE=hydro MACHINE=hpcperf GIT_HASH=$SHA; log $L3_LOGS/build-$MODEL.log)"
